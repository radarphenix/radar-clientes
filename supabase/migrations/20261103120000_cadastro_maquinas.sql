-- ------------------------------------------------------------------ funções
-- Nº da máquina comparável ("01" = "1").
create or replace function public.cadastro_maquinas_normalizar_numero(p text)
returns text language sql immutable set search_path = public as $$
  select nullif(regexp_replace(upper(regexp_replace(coalesce(p, ''), '\s', '', 'g')), '^0+', ''), '')
$$;

-- Visibilidade: não-representante vê tudo; representante vê clientes da carteira e os prospects que cadastrou.
create or replace function public.cadastro_maquinas_posso_ver(p_codigo_cliente text, p_criado_por uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select radar_perfil_atual_tipo() <> 'representante'
    or (p_codigo_cliente = 'PROSPECT' and p_criado_por = auth.uid())
    or (p_codigo_cliente <> 'PROSPECT' and exists (
          select 1 from clientes c
          where c.codigo_cliente::text = any (radar_codigos_numericos_equivalentes(p_codigo_cliente))
            and radar_na_minha_carteira(c.codigo_cliente::text, c.codigo_representante::text)))
$$;

-- Auditoria de quem grava pelo Radar. O sync (service_role, sem auth.uid()) grava os valores que traz.
create or replace function public.cadastro_maquinas_auditoria()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_nome text;
begin
  if auth.uid() is null then
    return new;
  end if;
  select p.nome into v_nome from perfis p where p.user_id = auth.uid() limit 1;
  if tg_op = 'INSERT' then
    new.id := nextval(pg_get_serial_sequence(tg_table_schema || '.' || tg_table_name, 'id'));
    if new.origem not in ('RADAR', 'FEIRA') then new.origem := 'RADAR'; end if;
    new.criado_por := auth.uid();
    new.criado_por_nome := v_nome;
    new.criado_em := now();
    new.sincronizado_em := null;
  else
    new.id := old.id;
    new.origem := old.origem;
    new.id_feira_origem := old.id_feira_origem;
    new.criado_por := old.criado_por;
    new.criado_por_nome := old.criado_por_nome;
    new.criado_em := old.criado_em;
    new.sincronizado_em := old.sincronizado_em;
  end if;
  new.atualizado_por := auth.uid();
  new.atualizado_por_nome := v_nome;
  new.atualizado_em := now();
  return new;
end;
$$;

drop trigger if exists cadastro_maquinas_auditoria on public.cadastro_maquinas;
create trigger cadastro_maquinas_auditoria before insert or update on public.cadastro_maquinas
  for each row execute function public.cadastro_maquinas_auditoria();
drop trigger if exists cadastro_maquinas_itens_auditoria on public.cadastro_maquinas_itens;
create trigger cadastro_maquinas_itens_auditoria before insert or update on public.cadastro_maquinas_itens
  for each row execute function public.cadastro_maquinas_auditoria();

-- "Sincronizar agora": registra o pedido; o sync atende na próxima verificação.
create or replace function public.cadastro_maquinas_solicitar_sync()
returns timestamptz language plpgsql security definer set search_path = public as $$
declare
  v_quando timestamptz := now();
begin
  if not radar_pode('maquinas.editar') then
    raise exception 'Sem permissão para solicitar a sincronização.';
  end if;
  update cadastro_maquinas_sync_status
     set solicitado_em = v_quando, solicitado_por = auth.uid(),
         solicitado_por_nome = (select p.nome from perfis p where p.user_id = auth.uid() limit 1)
   where id = 1;
  return v_quando;
end;
$$;

-- Texto da feira ("1.234,567", "12,5", "300") para número; inválido vira null.
create or replace function public.cadastro_maquinas_numero_feira(p text)
returns numeric language plpgsql immutable set search_path = public as $$
declare
  v text := replace(trim(coalesce(p, '')), ' ', '');
begin
  if v like '%,%' then v := replace(replace(v, '.', ''), ',', '.'); end if;
  if v ~ '^-?\d+(\.\d+)?$' then return v::numeric; end if;
  return null;
end;
$$;

-- Carga dos cadastros da feira Veste Phenix (origem FEIRA). Idempotente: não repete o que já veio.
-- Empresa com nome igual a um único cliente vira esse cliente; senão, prospect.
create or replace function public.cadastro_maquinas_importar_feira()
returns integer language plpgsql security definer set search_path = public as $$
declare
  g record;
  v_cliente text;
  v_qtd_clientes integer;
  v_maquina bigint;
  v_total integer := 0;
begin
  if not radar_pode('administracao') then
    raise exception 'Só administradores importam os cadastros da feira.';
  end if;

  for g in
    select coalesce(f.grupo_id, f.id) grupo,
           min(f.empresa) empresa, min(f.contato) contato, min(f.telefone) telefone, min(f.email) email,
           min(f.responsavel) responsavel, min(f.maquina) maquina, min(f.tipo_papel) tipo_papel,
           min(f.velocidade_maquina) velocidade, min(f.informacoes_adicionais) informacoes, min(f.criado_em) criado_em
      from cadastro_produtos_feira_phenix f
     where f.excluido_em is null
       and not exists (select 1 from cadastro_maquinas m where m.id_feira_origem = coalesce(f.grupo_id, f.id)::text)
     group by coalesce(f.grupo_id, f.id)
  loop
    select min(c.codigo_cliente::text), count(*) into v_cliente, v_qtd_clientes
      from clientes c where upper(trim(c.cliente)) = upper(trim(g.empresa));
    if v_qtd_clientes <> 1 then v_cliente := 'PROSPECT'; end if;

    insert into cadastro_maquinas (origem, id_feira_origem, codigo_cliente, nome_prospect, contato_prospect, telefone_prospect,
                                   nome_maquina, tipo_papel, velocidade_maquina, observacoes)
    values ('FEIRA', g.grupo::text, v_cliente, left(trim(g.empresa), 160), left(nullif(trim(g.contato), ''), 160),
            left(nullif(trim(g.telefone), ''), 30), left(nullif(trim(g.maquina), ''), 160), left(nullif(trim(g.tipo_papel), ''), 60),
            left(nullif(trim(g.velocidade), ''), 60),
            left(concat_ws(E'\n',
              'Cadastrado na feira Veste Phenix em ' || to_char(g.criado_em at time zone 'America/Sao_Paulo', 'DD/MM/YYYY') ||
                coalesce(' por ' || nullif(trim(g.responsavel), ''), ''),
              'E-mail: ' || nullif(trim(g.email), ''),
              nullif(trim(g.informacoes), '')), 4000))
    returning id into v_maquina;

    insert into cadastro_maquinas_itens (id_maquina, origem, id_feira_origem, produto, nome_produto_outros, modelo, posicao,
                                         comprimento, largura, espessura, cfm, gramatura, durabilidade, teflonada)
    select v_maquina, 'FEIRA', f.id::text, left(nullif(trim(f.produto), ''), 80), left(nullif(trim(f.nome_produto_outros), ''), 160),
           left(nullif(trim(f.modelo), ''), 80), left(nullif(trim(f.posicao), ''), 80),
           cadastro_maquinas_numero_feira(f.comprimento), cadastro_maquinas_numero_feira(f.largura),
           cadastro_maquinas_numero_feira(f.espessura), cadastro_maquinas_numero_feira(f.cfm),
           cadastro_maquinas_numero_feira(f.gramatura), left(nullif(trim(f.durabilidade), ''), 60),
           case when f.produto = 'Secadora Espiral' then f.teflonada end
      from cadastro_produtos_feira_phenix f
     where coalesce(f.grupo_id, f.id) = g.grupo and f.excluido_em is null and nullif(trim(f.produto), '') is not null
     order by f.produto, f.item;

    v_total := v_total + 1;
  end loop;
  return v_total;
end;
$$;

revoke all on function public.cadastro_maquinas_posso_ver(text, uuid), public.cadastro_maquinas_solicitar_sync(),
  public.cadastro_maquinas_importar_feira(), public.cadastro_maquinas_auditoria() from public, anon;
grant execute on function public.cadastro_maquinas_posso_ver(text, uuid), public.cadastro_maquinas_solicitar_sync(),
  public.cadastro_maquinas_importar_feira(), public.cadastro_maquinas_normalizar_numero(text) to authenticated;

