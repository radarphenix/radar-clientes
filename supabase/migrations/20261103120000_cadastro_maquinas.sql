insert into public.radar_permissoes_perfil (tipo_perfil, codigo, permitido)
select t.tipo, p.codigo, t.tipo in ('admin', 'tecnico', 'representante')
from (values ('admin'), ('tecnico'), ('representante'), ('qualidade')) t(tipo)
cross join (values ('maquinas'), ('maquinas.editar'), ('clientes.maquinas')) p(codigo)
on conflict (tipo_perfil, codigo) do nothing;

-- ------------------------------------------------------------------ tabelas
create table if not exists public.cadastro_maquinas (
  id bigint generated by default as identity (start with 1) primary key,
  origem text not null default 'RADAR' check (origem in ('RADAR', 'CIGAM', 'FEIRA')),
  id_feira_origem text unique,
  codigo_cliente text not null default 'PROSPECT' check (char_length(trim(codigo_cliente)) between 1 and 20),
  nome_prospect text check (char_length(nome_prospect) <= 160),
  cidade_prospect text check (char_length(cidade_prospect) <= 100),
  uf_prospect text check (char_length(uf_prospect) <= 2),
  contato_prospect text check (char_length(contato_prospect) <= 160),
  telefone_prospect text check (char_length(telefone_prospect) <= 30),
  nome_maquina text check (char_length(nome_maquina) <= 160),
  numero_maquina_pedido text check (char_length(numero_maquina_pedido) <= 6),
  tipo_papel text check (char_length(tipo_papel) <= 60),
  velocidade_maquina text check (char_length(velocidade_maquina) <= 60),
  observacoes text check (char_length(observacoes) <= 4000),
  ativo boolean not null default true,
  criado_por uuid,
  criado_por_nome text,
  criado_em timestamptz not null default now(),
  atualizado_por uuid,
  atualizado_por_nome text,
  atualizado_em timestamptz not null default now(),
  sincronizado_em timestamptz,
  constraint cadastro_maquinas_faixa_id check ((origem = 'CIGAM') = (id >= 10000000)),
  constraint cadastro_maquinas_prospect check (codigo_cliente <> 'PROSPECT' or char_length(trim(coalesce(nome_prospect, ''))) >= 2)
);
-- (nome nulo passava na regra acima sem o coalesce: check aceita resultado nulo)
