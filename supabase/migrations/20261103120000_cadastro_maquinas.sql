-- Cadastro de Máquinas (irmão do CIGAM: EX_MW_CAD_MAQUINA / EX_MW_CAD_MAQUINA_ITEM).
-- Contrato completo em ../01_Desktop/MWCadastroMaquinas/Docs/CADASTRO_MAQUINAS.md.
--
-- IDs: Radar de 1 a 9.999.999 (identity); CIGAM a partir de 10.000.000 (sequence Oracle).
-- O sync grava o registro do outro lado com o mesmo ID. ORIGEM: RADAR | CIGAM | FEIRA.
-- Prospect: codigo_cliente = 'PROSPECT' (código reservado) + nome_prospect. Tudo o mais é opcional.
-- Pendente de envio ao CIGAM: sincronizado_em is null or atualizado_em > sincronizado_em.
-- Exclusão é só ativo = false (sem política de delete).

